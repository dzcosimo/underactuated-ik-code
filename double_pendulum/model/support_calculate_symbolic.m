% SUPPORT_CALCULATE_SYMBOLIC  Symbolic derivation of the actuation-coordinate terms of the
% tendon-driven double pendulum (paper Secs. 2.3-2.5.1) and code generation.
%
% Generates, into model/generated/, the functions used by the simulations:
%   q_to_q_act(q1,q2,alpha,r1,r2)         (qa;qu) = T^-1 q                       Eq. (16), (19)
%   q_act_to_q(qa,qu,alpha,r1,r2)         q = T (qa;qu)
%   Jacobian_q_act_to_q(qa,qu,alpha,r1,r2) T = dq/d(qa,qu) (constant)
%   GuFunction_supp(alpha,r1,r2,G1,G2)    Gu = [0 1] T' G   (unactuated potential force, Eq. (17))
%   GaFunction_supp(alpha,r1,r2,G1,G2)    Ga = [1 0] T' G   (actuated potential force)
%   HuaFunction_supp(qa,qu,alpha,r1,r2,m1,m2,g,l1,l2,k1,k2)  Hua = dGu/dqa   (used in Eq. (43))
%   HuuFunction_supp(...)                                    Huu = dGu/dqu
%   JaFunction_supp(qa,qu,alpha,r1,r2,l1,l2)  Ja = dh/dqa   (task Jacobian blocks, Eq. (43))
%   JuFunction_supp(qa,qu,alpha,r1,r2,l1,l2)  Ju = dh/dqu
%
% Conventions (as in the original code):
%   * A = [r1; r2] (Eq. (5)); T = inv([A'; (R(alpha) A)']), i.e. qa = A' q and qu is the
%     projection on A rotated by alpha (Sec. 2.5.1). All paper cases use alpha = pi/2.
%   * Angles are measured from the downward vertical (gravity direction). The task is the
%     horizontal end-effector coordinate. It is written here as in the original
%     code, l1 cos(q1 - pi/2) + l2 cos(q1 + q2 - pi/2) (= l1 sin q1 + l2 sin(q1+q2)).
%
% Requires the Symbolic Math Toolbox. You do not need to run it: the generated functions are
% shipped. Run it from any folder: it writes next to this file, into model/generated/.
%
% Difference from the original script: the Hessian blocks Hua, Huu are obtained by substituting
% q = T (qa;qu) (the original substituted q = inv(T') (qa;qu)). The two coincide when T is
% orthogonal, i.e. alpha = pi/2 and ||A|| = 1, which holds in every case of the paper. With
% q = T (qa;qu) the result is also correct for other alpha.

outdir = fullfile(fileparts(mfilename('fullpath')), 'generated');
if ~exist(outdir, 'dir'), mkdir(outdir); end
hdr = @(s) {s, 'Double pendulum of Sec. 2.3, generated by model/support_calculate_symbolic.m.'};

syms alpha q1 q2 r1 r2 G1 G2 k1 k2 real
syms qu qa real
syms m1 m2 g l1 l2 real

% Change of coordinates to actuation coordinates (Eqs. (8), (16)).
A = [r1; r2];
Ralpha = [cos(alpha), -sin(alpha); sin(alpha), cos(alpha)];
T = inv([A'; (Ralpha*A)']);
assert(all(isAlways(simplify(T'*A) == [1; 0], 'Unknown', 'false')), 'T does not map A to the first actuation coordinate');

matlabFunction(inv(T)*[q1;q2], 'File', fullfile(outdir,'q_to_q_act'), 'Vars', [q1, q2, alpha, r1, r2], ...
    'Comments', hdr('From joint angles q to actuation coordinates (qa;qu), Eq. (16).'));
matlabFunction(T*[qa;qu], 'File', fullfile(outdir,'q_act_to_q'), 'Vars', [qa, qu, alpha, r1, r2], ...
    'Comments', hdr('From actuation coordinates (qa;qu) to joint angles q = T (qa;qu).'));
matlabFunction(T, 'File', fullfile(outdir,'Jacobian_q_act_to_q'), 'Vars', [qa, qu, alpha, r1, r2], ...
    'Comments', hdr('Jacobian dq/d(qa,qu) = T (constant).'));

% Potential forces in actuation coordinates: [Ga; Gu] = T' G (Eq. (17)).
Gu = simplify([0 1]*T'*[G1; G2]);
Ga = simplify([1 0]*T'*[G1; G2]);
matlabFunction(Gu, 'File', fullfile(outdir,'GuFunction_supp'), 'Vars', [alpha, r1, r2, G1, G2], ...
    'Comments', hdr('Unactuated potential force Gu = [0 1] T^T G, Eq. (17).'));
matlabFunction(Ga, 'File', fullfile(outdir,'GaFunction_supp'), 'Vars', [alpha, r1, r2, G1, G2], ...
    'Comments', hdr('Actuated potential force Ga = [1 0] T^T G.'));

% Hessian blocks of Gu w.r.t. (qa,qu): G(q) of Eq. (6) (gravity + parallel springs).
G_sym = [m1*g*l1*sin(q1) + m2*g*(l1*sin(q1) + l2*sin(q1 + q2)) + k1*q1;
         m2*g*l2*sin(q1 + q2) + k2*q2];
Gu_ac = subs(subs(Gu, [G1; G2], G_sym), [q1; q2], T*[qa; qu]);
Hu_all = simplify(gradient(Gu_ac, [qa; qu]));
matlabFunction(Hu_all(1), 'File', fullfile(outdir,'HuaFunction_supp'), ...
    'Vars', [qa, qu, alpha, r1, r2, m1, m2, g, l1, l2, k1, k2], ...
    'Comments', hdr('Hua = dGu/dqa (Hessian block in Eq. (43)).'));
matlabFunction(Hu_all(2), 'File', fullfile(outdir,'HuuFunction_supp'), ...
    'Vars', [qa, qu, alpha, r1, r2, m1, m2, g, l1, l2, k1, k2], ...
    'Comments', hdr('Huu = dGu/dqu (Hessian block in Eq. (43)).'));

% Task Jacobian blocks in actuation coordinates (Eq. (43)).
x = l1*cos(q1 - pi/2) + l2*cos(q1 + q2 - pi/2);     % horizontal end-effector position
x_ac = subs(x, [q1; q2], T*[qa; qu]);
J_all = simplify(gradient(x_ac, [qa; qu]));
matlabFunction(J_all(1), 'File', fullfile(outdir,'JaFunction_supp'), 'Vars', [qa, qu, alpha, r1, r2, l1, l2], ...
    'Comments', hdr('Ja = dh/dqa (task Jacobian block in Eq. (43)).'));
matlabFunction(J_all(2), 'File', fullfile(outdir,'JuFunction_supp'), 'Vars', [qa, qu, alpha, r1, r2, l1, l2], ...
    'Comments', hdr('Ju = dh/dqu (task Jacobian block in Eq. (43)).'));

fprintf('Generated functions written to %s\n', outdir);
